// Calls: events the community forecast saw coming, often before the experts,
// markets or officials it is compared against. Each carries a daily snapshot
// of the community prediction on one resolved question (P(yes), last value
// of each UTC day) from shortly before the call through the reference date.
// The snapshots are static because the questions are resolved; regenerate
// with metaculus-db-tools/projects/about-chart-calls/gen_calls.py.

export type CallSeries = [string, number][];

export type ChartCall = {
  postId: number;
  // Translation keys: the question title, and the outside source the call
  // beat ("WHO, Dec 14, 2021: ...")
  questionKey: string;
  versusKey: string;
  // "above": the call is the forecast at or above the threshold (the event
  // happened). "below": the forecast below it (the event did not).
  direction: "above" | "below";
  threshold: number;
  series: CallSeries;
};

export type LeadUp = {
  // First day of the final unbroken run on the called side of the threshold
  since: string;
  // Days from `since` to the event's date
  days: number;
  // Index of `since` in the series
  sinceIndex: number;
};

const DAY_MS = 24 * 60 * 60 * 1000;
const dayMs = (date: string) => Date.parse(`${date}T00:00:00Z`);

export const onCalledSide = (call: ChartCall, value: number) =>
  call.direction === "above" ? value >= call.threshold : value < call.threshold;

// How early the call was: the forecast reached the called side and stayed
// there, without crossing back, until the event (or until the question
// closed, if that came first). Earlier crossings that fell back don't count.
// Null when the forecast was on the wrong side going in.
export function leadUp(call: ChartCall, eventDate: string): LeadUp | null {
  const { series } = call;
  const last = series[series.length - 1];
  if (!last || !onCalledSide(call, last[1])) return null;
  let sinceIndex = series.length - 1;
  while (
    sinceIndex > 0 &&
    onCalledSide(call, series[sinceIndex - 1]?.[1] ?? NaN)
  ) {
    sinceIndex--;
  }
  const since = series[sinceIndex]?.[0] ?? last[0];
  const days = Math.round((dayMs(eventDate) - dayMs(since)) / DAY_MS);
  return { since, days, sinceIndex };
}

