/**
 * Freezes a Global Health Monitor edition at publication, so it keeps showing its
 * publication-day forecasts once it's no longer the latest. Run it right before merging an edition.
 *
 *   bun run ghm:bake --slug 2026-10
 *
 * It prints the `asOf` and `frozen` blocks to paste into the edition, and writes
 * `editions/archives/edition_YYYY_MM.ts`: the current section layout plus the Community
 * Prediction distribution of every numeric, discrete and date question.
 *
 * --slug  edition month (YYYY-MM)
 * --at    backfill the archive of an edition published at this instant (ISO) instead; its
 *         distributions come from the aggregation explorer, and nothing is printed
 * --api   API base URL (defaults to METACULUS_API_BASE_URL, then https://www.metaculus.com/api)
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

import { apiGet, ApiConfig, fetchGhmPostsFromApi, getApiConfig } from "./api";
import {
  GHM_VALUE_KEYS,
  GHM_VALUES,
  ValueRef,
} from "../../src/app/(main)/global-health-monitor/config/questions";
import { SECTIONS } from "../../src/app/(main)/global-health-monitor/config/sections";
import {
  EditionArchive,
  FrozenValue,
} from "../../src/app/(main)/global-health-monitor/editions/types";
import {
  findAggregateAt,
  findQuestion,
  getDefaultAggregation,
  readLatestForecast,
} from "../../src/app/(main)/global-health-monitor/helpers/forecast_values";
import { PostWithForecasts } from "../../src/types/post";
import { QuestionType, QuestionWithForecasts } from "../../src/types/question";

const ARCHIVES_DIR = "src/app/(main)/global-health-monitor/editions/archives";
const CONTINUOUS_TYPES: QuestionType[] = [
  QuestionType.Numeric,
  QuestionType.Discrete,
  QuestionType.Date,
];

function round(value: number, ref: ValueRef) {
  return ref.format.kind === "date"
    ? Math.round(value)
    : Math.round(value * 10_000) / 10_000;
}

function roundCdf(cdf: number[]) {
  return cdf.map((value) => Math.round(value * 10_000) / 10_000);
}

function bakeFrozen(posts: Map<number, PostWithForecasts>) {
  const frozen: Record<string, FrozenValue> = {};
  for (const key of GHM_VALUE_KEYS) {
    const ref: ValueRef = GHM_VALUES[key];
    const question = findQuestion(posts.get(ref.postId), ref);
    const latest = question ? readLatestForecast(question, ref) : null;
    if (!latest) {
      continue;
    }
    frozen[key] = {
      value: round(latest.value, ref),
      ...(latest.lower !== null ? { lower: round(latest.lower, ref) } : {}),
      ...(latest.upper !== null ? { upper: round(latest.upper, ref) } : {}),
      ...(latest.bound ? { bound: latest.bound } : {}),
      ...(ref.option === "top" && latest.option
        ? { option: latest.option }
        : {}),
    };
  }
  return frozen;
}

function getContinuousQuestions(posts: Map<number, PostWithForecasts>) {
  const questions: { postId: number; question: QuestionWithForecasts }[] = [];
  for (const post of posts.values()) {
    const postQuestions: QuestionWithForecasts[] = post.question
      ? [post.question]
      : post.group_of_questions?.questions ?? [];
    for (const question of postQuestions) {
      if (CONTINUOUS_TYPES.includes(question.type)) {
        questions.push({ postId: post.id, question });
      }
    }
  }
  return questions;
}

// The aggregation explorer recomputes the full history, distributions included.
async function readCdfAt(
  config: ApiConfig,
  question: QuestionWithForecasts,
  timestamp: number
): Promise<number[] | null> {
  const explored = await apiGet<QuestionWithForecasts>(
    config,
    "/aggregation_explorer/",
    {
      question_id: question.id,
      aggregation_methods: question.default_aggregation_method,
    }
  );
  const history = getDefaultAggregation(explored)?.history ?? [];
  return findAggregateAt(history, timestamp)?.forecast_values ?? null;
}

async function bakeDistributions(
  config: ApiConfig,
  posts: Map<number, PostWithForecasts>,
  at: number | null
) {
  const distributions: EditionArchive["distributions"] = {};
  for (const { postId, question } of getContinuousQuestions(posts)) {
    const cdf =
      at === null
        ? getDefaultAggregation(question)?.latest?.forecast_values
        : await readCdfAt(config, question, at);
    if (cdf?.length) {
      distributions[question.id] = { postId, cdf: roundCdf(cdf) };
    } else {
      console.warn(`No distribution for question ${question.id}`);
    }
  }
  return distributions;
}

async function writeArchive(slug: string, archive: EditionArchive) {
  const [year, month] = slug.split("-");
  const name = `${year}_${month}`;
  const file = path.resolve(process.cwd(), ARCHIVES_DIR, `edition_${name}.ts`);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(
    file,
    [
      `// Generated by \`bun run ghm:bake --slug ${slug}\`. Don't edit by hand.`,
      `import { EditionArchive } from "../types";`,
      "",
      `export const ARCHIVE_${name}: EditionArchive = ${JSON.stringify(archive)};`,
      "",
    ].join("\n")
  );
  return file;
}

async function main() {
  const { values: args } = parseArgs({
    options: {
      slug: { type: "string" },
      at: { type: "string" },
      api: { type: "string" },
    },
  });
  if (!args.slug || !/^\d{4}-\d{2}$/.test(args.slug)) {
    throw new Error("Pass the edition month as --slug YYYY-MM");
  }
  const at = args.at ? Math.floor(Date.parse(args.at) / 1000) : null;
  if (at !== null && Number.isNaN(at)) {
    throw new Error(`Invalid --at: ${args.at}`);
  }

  const asOf = new Date().toISOString();
  const config = getApiConfig(args.api);
  const posts = await fetchGhmPostsFromApi(config);
  const file = await writeArchive(args.slug, {
    layout: SECTIONS,
    distributions: await bakeDistributions(config, posts, at),
  });
  console.error(`Wrote ${path.relative(process.cwd(), file)}`);

  if (at === null) {
    console.log(`asOf: "${asOf}",`);
    console.log(`frozen: ${JSON.stringify(bakeFrozen(posts), null, 2)},`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
